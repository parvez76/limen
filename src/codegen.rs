        assert!(g.code.contains("async fn get(u: &str) -> anyhow::Result<String> {\n    Ok(reqwest::get(u).await?.text().await?)\n}"), "{}", g.code);
        assert!(g.code.contains("#[tokio::main]\nasync fn main() -> anyhow::Result<()> {"));
        assert!(g.code.contains("let e = serde_json::from_str::<Ev>(&raw)?;"));
