/// WebSocket runtime for `socket` routes: `Conn` (receive + send), a cloneable
/// `WsSender` (bounded queue drained by a writer task that also pings), `WsMsg`.
const WS_PRELUDE: &str = r#"

/// One received WebSocket message.
#[derive(Debug, Clone, PartialEq)]
pub enum WsMsg {
    Text(String),
    Binary(Vec<u8>),
}

impl WsMsg {
    pub fn is_text(&self) -> bool {
        matches!(self, WsMsg::Text(_))
    }

    pub fn len(&self) -> usize {
        match self {
            WsMsg::Text(t) => t.len(),
            WsMsg::Binary(b) => b.len(),
        }
    }

    /// The text (binary is decoded lossily).
    pub fn text(&self) -> String {
        match self {
            WsMsg::Text(t) => t.clone(),
            WsMsg::Binary(b) => String::from_utf8_lossy(b).into_owned(),
        }
    }

    pub fn bytes(&self) -> Vec<u8> {
        match self {
            WsMsg::Text(t) => t.as_bytes().to_vec(),
            WsMsg::Binary(b) => b.clone(),
        }
    }

    fn into_message(self) -> axum::extract::ws::Message {
        match self {
            WsMsg::Text(t) => axum::extract::ws::Message::Text(t.into()),
            WsMsg::Binary(b) => axum::extract::ws::Message::Binary(b.into()),
        }
    }
}

enum WsOut {
    Msg(axum::extract::ws::Message),
    Close(u16, String),
}

static WS_IDS: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(1);

/// A handle for sending to one connection from anywhere (other tasks, shared
/// state). Sends never block: if the client is too slow (queue of 64 full) or
/// gone, the frame is dropped and `false` is returned.
#[derive(Clone)]
pub struct WsSender {
    id: u64,
    tx: tokio::sync::mpsc::Sender<WsOut>,
}

impl std::fmt::Debug for WsSender {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "WsSender({})", self.id)
    }
}

impl PartialEq for WsSender {
    fn eq(&self, other: &Self) -> bool {
        self.id == other.id
    }
}

impl WsSender {
    pub fn id(&self) -> u64 {
        self.id
    }

    /// Is this the same connection as `other`?
    pub fn same(&self, other: &WsSender) -> bool {
        self.id == other.id
    }

    pub fn text(&self, s: impl Into<String>) -> bool {
        self.tx.try_send(WsOut::Msg(axum::extract::ws::Message::Text(s.into().into()))).is_ok()
    }

    pub fn bytes(&self, b: impl Into<Vec<u8>>) -> bool {
        self.tx.try_send(WsOut::Msg(axum::extract::ws::Message::Binary(b.into().into()))).is_ok()
    }

    /// Relays a received message unchanged (text stays text, binary stays binary).
    pub fn send(&self, m: &WsMsg) -> bool {
        self.tx.try_send(WsOut::Msg(m.clone().into_message())).is_ok()
    }

    pub fn json<T: serde::Serialize>(&self, v: &T) -> bool {
        serde_json::to_string(v).map(|s| self.text(s)).unwrap_or(false)
    }

    /// Closes the connection with a WebSocket close code (1000 normal, 1008 policy, ...).
    pub fn close(&self, code: u16, reason: impl Into<String>) {
        let _ = self.tx.try_send(WsOut::Close(code, reason.into()));
    }
}

/// The connection a `socket` handler receives as `conn`.
pub struct Conn {
    rx: futures::stream::SplitStream<axum::extract::ws::WebSocket>,
    out: WsSender,
    writer: tokio::task::JoinHandle<()>,
    protocol: Option<String>,
}

impl Conn {
    fn new(socket: axum::extract::ws::WebSocket) -> Conn {
        use futures::{SinkExt, StreamExt};
        use axum::extract::ws::Message;
        let protocol = socket.protocol().and_then(|p| p.to_str().ok()).map(String::from);
        let (mut sink, rx) = socket.split();
        let (tx, mut out_rx) = tokio::sync::mpsc::channel::<WsOut>(64);
        let writer = tokio::spawn(async move {
            let every = std::time::Duration::from_secs(limit("PARVEZ_WS_PING_SECS", 20).max(1));
            let mut ping = tokio::time::interval(every);
            ping.tick().await;
            loop {
                tokio::select! {
                    next = out_rx.recv() => match next {
                        Some(WsOut::Msg(m)) => {
                            let sent = tokio::time::timeout(std::time::Duration::from_secs(15), sink.send(m)).await;
                            if !matches!(sent, Ok(Ok(()))) {
                                break;
                            }
                        }
                        Some(WsOut::Close(code, reason)) => {
                            let frame = axum::extract::ws::CloseFrame { code, reason: reason.into() };
                            let _ = sink.send(Message::Close(Some(frame))).await;
                            break;
                        }
                        None => break,
                    },
                    _ = ping.tick() => {
                        if sink.send(Message::Ping(Vec::new().into())).await.is_err() {
                            break;
                        }
                    }
                }
            }
            let _ = sink.close().await;
        });
        let id = WS_IDS.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
        Conn { rx, out: WsSender { id, tx }, writer, protocol }
    }

    /// The next message, or `None` once the client has closed. Pings are answered for you.
    pub async fn recv(&mut self) -> anyhow::Result<Option<WsMsg>> {
        use futures::StreamExt;
        use axum::extract::ws::Message;
        while let Some(m) = self.rx.next().await {
            match m? {
                Message::Text(t) => return Ok(Some(WsMsg::Text(t.to_string()))),
                Message::Binary(b) => return Ok(Some(WsMsg::Binary(b.to_vec()))),
                Message::Close(_) => return Ok(None),
                _ => {}
            }
        }
        Ok(None)
    }

    /// The next text message parsed as JSON (`None` once closed).
    pub async fn recv_json<T: serde::de::DeserializeOwned>(&mut self) -> anyhow::Result<Option<T>> {
        match self.recv().await? {
            Some(m) => Ok(Some(serde_json::from_str(&m.text())?)),
            None => Ok(None),
        }
    }

    /// A cloneable sender for this connection (store it in state, use it from other tasks).
    pub fn sender(&self) -> WsSender {
        self.out.clone()
    }

    /// The negotiated subprotocol (see `@protocols`).
    pub fn protocol(&self) -> Option<String> {
        self.protocol.clone()
    }

    async fn queue(&self, m: axum::extract::ws::Message) -> anyhow::Result<()> {
        self.out.tx.send(WsOut::Msg(m)).await.map_err(|_| anyhow::anyhow!("connection closed"))
    }

    /// Sends text, waiting for queue space (unlike `WsSender`, never drops).
    pub async fn send_text(&self, s: impl Into<String>) -> anyhow::Result<()> {
        self.queue(axum::extract::ws::Message::Text(s.into().into())).await
    }

    pub async fn send_bytes(&self, b: impl Into<Vec<u8>>) -> anyhow::Result<()> {
        self.queue(axum::extract::ws::Message::Binary(b.into().into())).await
    }

    pub async fn send_json<T: serde::Serialize>(&self, v: &T) -> anyhow::Result<()> {
        self.send_text(serde_json::to_string(v)?).await
    }

    pub fn close(&self, code: u16, reason: impl Into<String>) {
        self.out.close(code, reason);
    }

    /// After the handler returns: close normally, give the writer 5s to flush.
    async fn finish(self) {
        self.out.close(1000, "bye");
        let mut writer = self.writer;
        if tokio::time::timeout(std::time::Duration::from_secs(5), &mut writer).await.is_err() {
            writer.abort();
        }
    }
}"#;

