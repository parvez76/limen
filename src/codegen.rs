const SESSION_CHUNKS: usize = 4;
const CHUNK: usize = 3800;

fn now_secs() -> u64 {
    std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).map(|d| d.as_secs()).unwrap_or(0)
}

fn request_cookies(headers: &axum::http::HeaderMap) -> Vec<(String, String)> {
    headers
        .get_all(axum::http::header::COOKIE)
        .iter()
        .filter_map(|v| v.to_str().ok())
        .flat_map(|v| v.split(';'))
        .filter_map(|kv| kv.trim().split_once('=').map(|(k, v)| (k.to_string(), v.to_string())))
        .collect()
}

/// The encrypted session, split over `name.0`, `name.1`, ... (browsers cap cookies at ~4 KB).
fn session_cookies(cfg: &SessionConfig, data: &SessionData) -> Vec<String> {
    let name = cfg.cookie_name("parvez_session");
    let sealed = cfg.seal(&name, &serde_json::to_vec(data).unwrap_or_default());
    let chunks: Vec<&str> = sealed.as_bytes().chunks(CHUNK).map(|c| std::str::from_utf8(c).unwrap_or("")).collect();
    let mut out: Vec<String> = chunks.iter().enumerate().map(|(i, c)| cfg.cookie(&format!("{name}.{i}"), c, cfg.max_age)).collect();
    for i in chunks.len()..SESSION_CHUNKS {
        out.push(cfg.cookie(&format!("{name}.{i}"), "", 0));
    }
    out
}

fn clear_session(cfg: &SessionConfig) -> Vec<String> {
    let name = cfg.cookie_name("parvez_session");
    (0..SESSION_CHUNKS).map(|i| cfg.cookie(&format!("{name}.{i}"), "", 0)).collect()
}

fn read_session(cfg: &SessionConfig, headers: &axum::http::HeaderMap) -> Option<SessionData> {
    let name = cfg.cookie_name("parvez_session");
    let jar = request_cookies(headers);
    let mut sealed = String::new();
    for i in 0..SESSION_CHUNKS {
        match jar.iter().find(|(k, _)| *k == format!("{name}.{i}")) {
            Some((_, v)) if !v.is_empty() => sealed.push_str(v),
            _ => break,
        }
    }
    if sealed.is_empty() {
        return None;
    }
    let data: SessionData = serde_json::from_slice(&cfg.open(&name, &sealed)?).ok()?;
    (now_secs().saturating_sub(data.iat) <= cfg.max_age).then_some(data)
}

/// Discovery document, cached 10 minutes.
async fn oidc_discovery() -> anyhow::Result<serde_json::Value> {
    static CACHE: std::sync::OnceLock<tokio::sync::Mutex<Option<(serde_json::Value, std::time::Instant)>>> = std::sync::OnceLock::new();
    let mut c = CACHE.get_or_init(|| tokio::sync::Mutex::new(None)).lock().await;
    if let Some((doc, at)) = c.as_ref()
        && at.elapsed() < std::time::Duration::from_secs(600)
    {
        return Ok(doc.clone());
    }
    let issuer = oidc_issuer()?;
    let client = reqwest::Client::builder().timeout(std::time::Duration::from_secs(10)).build()?;
    let doc: serde_json::Value =
        client.get(format!("{issuer}/.well-known/openid-configuration")).send().await?.error_for_status()?.json().await?;
    *c = Some((doc.clone(), std::time::Instant::now()));
    Ok(doc)
}

fn random_token() -> String {
    use aes_gcm::aead::rand_core::RngCore;
    use base64::Engine;
    let mut b = [0u8; 32];
    aes_gcm::aead::OsRng.fill_bytes(&mut b);
    base64::engine::general_purpose::URL_SAFE_NO_PAD.encode(b)
}

/// Token endpoint call (authorization_code or refresh_token grant).
async fn token_request(cfg: &SessionConfig, form: &[(&str, &str)]) -> anyhow::Result<SessionData> {
    let doc = oidc_discovery().await?;
    let endpoint = doc["token_endpoint"].as_str().ok_or_else(|| anyhow::anyhow!("discovery has no token_endpoint"))?;
    let mut form: Vec<(&str, &str)> = form.to_vec();
    form.push(("client_id", &cfg.client_id));
    if let Some(sec) = &cfg.client_secret {
        form.push(("client_secret", sec));
    }
    let client = reqwest::Client::builder().timeout(std::time::Duration::from_secs(10)).build()?;
    let res = client.post(endpoint).form(&form).send().await?;
    if !res.status().is_success() {
        anyhow::bail!("token endpoint answered {}", res.status());
    }
    let v: serde_json::Value = res.json().await?;
    let at = v["access_token"].as_str().ok_or_else(|| anyhow::anyhow!("no access_token in token response"))?;
    Ok(SessionData { at: at.to_string(), rt: v["refresh_token"].as_str().map(String::from), iat: now_secs(), chk: now_secs() })
}

