//! AST -> idiomatic, formatted Rust source. Type checking and borrow
//! checking are delegated to rustc.

use crate::ast::*;
use std::collections::HashMap;

pub fn generate(prog: &Program) -> String {
    let mut g = Gen::default();
    for item in &prog.items {
        match item {
            Item::Fn(f) => {
                g.fns.insert(f.name.clone(), f.params.iter().map(|(_, t)| t.clone()).collect());
            }
            Item::Struct(s) => {
                g.structs.insert(s.name.clone(), s.fields.iter().cloned().collect());
            }
        }
    }
    g.out.push_str("// Generated by parvez v0.1. Plain Rust, no runtime: safe to keep and edit by hand.\n");
    g.out.push_str("#![allow(unused)]\n");
    for item in &prog.items {
        g.out.push('\n');
        match item {
            Item::Struct(s) => g.gen_struct(s),
            Item::Fn(f) => g.gen_fn(f),
        }
    }
    g.out
}

#[derive(Default)]
struct Gen {
    out: String,
    indent: usize,
    /// name -> is_mutable, one map per lexical block
    scopes: Vec<HashMap<String, bool>>,
    fallible: bool,
    ret_ty: Option<Type>,
    /// fn name -> parameter types (for string-literal coercion at call sites)
    fns: HashMap<String, Vec<Type>>,
    /// struct name -> field types
    structs: HashMap<String, HashMap<String, Type>>,
}

/// Does a value of this type need an owned String (vs a borrowed `&str`)?
fn owned(t: &Type) -> bool {
    !matches!(t, Type::Ref(..))
}

pub fn rust_type(t: &Type) -> String {
    match t {
        Type::Named(n, args) => {
            let base = if n == "str" { "String" } else { n.as_str() };
            if args.is_empty() {
                base.to_string()
            } else {
                let a: Vec<String> = args.iter().map(rust_type).collect();
                format!("{base}<{}>", a.join(", "))
            }
        }
        Type::Ref(inner, m) => {
            let m = if *m { "mut " } else { "" };
            match &**inner {
                Type::Named(n, a) if n == "str" && a.is_empty() => format!("&{m}str"),
                Type::List(e) => format!("&{m}[{}]", rust_type(e)),
                other => format!("&{m}{}", rust_type(other)),
            }
        }
        Type::List(e) => format!("Vec<{}>", rust_type(e)),
        Type::Opt(e) => format!("Option<{}>", rust_type(e)),
    }
}

impl Gen {
    fn line(&mut self, s: &str) {
        for _ in 0..self.indent {
            self.out.push_str("    ");
        }
        self.out.push_str(s);
        self.out.push('\n');
    }

    fn gen_struct(&mut self, s: &StructDef) {
        self.line("#[derive(Debug, Clone)]");
        self.line(&format!("struct {} {{", s.name));
        self.indent += 1;
        for (name, ty) in &s.fields {
            self.line(&format!("{name}: {},", rust_type(ty)));
        }
        self.indent -= 1;
        self.line("}");
    }

    fn gen_fn(&mut self, f: &FnDef) {
        let params: Vec<String> =
            f.params.iter().map(|(n, t)| format!("{n}: {}", rust_type(t))).collect();
        let ret = match (&f.ret, f.fallible) {
            (None, false) => String::new(),
            (None, true) => " -> anyhow::Result<()>".into(),
            (Some(t), false) => format!(" -> {}", rust_type(t)),
            (Some(t), true) => format!(" -> anyhow::Result<{}>", rust_type(t)),
        };
        self.line(&format!("fn {}({}){} {{", f.name, params.join(", "), ret));
        self.fallible = f.fallible;
        self.ret_ty = f.ret.clone();
        self.indent += 1;
        self.scopes.push(f.params.iter().map(|(n, _)| (n.clone(), false)).collect());

        let (last, init) = match f.body.split_last() {
            Some((l, i)) => (Some(l), i),
            None => (None, &f.body[..]),
        };
        for s in init {
            self.gen_stmt(s);
        }
        // Tail position: idiomatic implicit return.
        match last {
            Some(Stmt::Ret(Some(e))) => {
                let v = self.ret_expr(e);
                self.line(&self.wrap_ok(v));
            }
            Some(Stmt::Ret(None)) => {
                if f.fallible {
                    self.line("Ok(())");
                }
            }
            Some(Stmt::Expr(e)) if f.ret.is_some() && !is_diverging(e) => {
                let v = self.ret_expr(e);
                self.line(&self.wrap_ok(v));
            }
            Some(s) => {
                self.gen_stmt(s);
                if f.fallible && f.ret.is_none() && !matches!(s, Stmt::Expr(e) if is_diverging(e)) {
                    self.line("Ok(())");
                }
            }
            None => {
                if f.fallible {
                    self.line("Ok(())");
                }
            }
        }

        self.scopes.pop();
        self.indent -= 1;
        self.line("}");
    }

    fn ret_expr(&mut self, e: &Expr) -> String {
        let o = self.ret_ty.as_ref().is_none_or(owned);
        self.expr_as(e, o)
    }

    fn wrap_ok(&self, v: String) -> String {
        if self.fallible { format!("Ok({v})") } else { v }
    }

    fn block(&mut self, stmts: &[Stmt], bind: Option<&str>) {
        self.indent += 1;
        let mut scope = HashMap::new();
        if let Some(b) = bind {
            scope.insert(b.to_string(), false);
        }
        self.scopes.push(scope);
        for s in stmts {
            self.gen_stmt(s);
        }
        self.scopes.pop();
        self.indent -= 1;
    }

    fn is_mutable(&self, name: &str) -> bool {
        self.scopes.iter().rev().find_map(|s| s.get(name)).copied().unwrap_or(false)
    }

    fn gen_stmt(&mut self, s: &Stmt) {
        match s {
            Stmt::Let { name, mutable, ty, value } => {
                let v = self.expr_as(value, ty.as_ref().is_none_or(owned));
                if !mutable && ty.is_none() && self.is_mutable(name) {
                    self.line(&format!("{name} = {v};"));
                    return;
                }
                self.scopes.last_mut().unwrap().insert(name.clone(), *mutable);
                let m = if *mutable { "mut " } else { "" };
                let t = ty.as_ref().map(|t| format!(": {}", rust_type(t))).unwrap_or_default();
                self.line(&format!("let {m}{name}{t} = {v};"));
            }
            Stmt::Assign { target, op, value } => {
                let t = self.expr(target);
                let v = self.expr(value);
                self.line(&format!("{t} {op} {v};"));
            }
            Stmt::Expr(e) => {
                let v = self.expr(e);
                self.line(&format!("{v};"));
            }
            Stmt::Ret(e) => {
                let v = match e {
                    Some(e) => self.ret_expr(e),
                    None => "()".into(),
                };
                let v = if self.fallible {
                    format!("Ok({v})")
                } else if e.is_none() {
                    String::new()
                } else {
                    v
                };
                if v.is_empty() {
                    self.line("return;");
                } else {
                    self.line(&format!("return {v};"));
                }
            }
            Stmt::If { branches, els } => {
                for (i, (cond, body)) in branches.iter().enumerate() {
                    let c = self.expr(cond);
                    if i == 0 {
                        self.line(&format!("if {c} {{"));
                    } else {
                        self.line(&format!("}} else if {c} {{"));
                    }
                    self.block(body, None);
                }
                if let Some(body) = els {
                    self.line("} else {");
                    self.block(body, None);
                }
                self.line("}");
            }
            Stmt::For { var, iter, body } => {
                let it = self.expr(iter);
                self.line(&format!("for {var} in {it} {{"));
                self.block(body, Some(var));
                self.line("}");
            }
            Stmt::While { cond, body } => {
                let c = self.expr(cond);
                self.line(&format!("while {c} {{"));
                self.block(body, None);
                self.line("}");
            }
            Stmt::Break => self.line("break;"),
            Stmt::Continue => self.line("continue;"),
        }
    }

    /// Builds the `"fmt", args...` part of a formatting macro.
    fn fmt_args(&mut self, args: &[Expr]) -> String {
        let mut fmt = Vec::new();
        let mut vals = Vec::new();
        for a in args {
            match a {
                Expr::Str(parts) => {
                    let (f, v) = self.str_parts(parts);
                    fmt.push(f);
                    vals.extend(v);
                }
                other => {
                    fmt.push("{}".into());
                    vals.push(self.expr_loose(other));
                }
            }
        }
        let mut s = format!("\"{}\"", fmt.join(" "));
        for v in vals {
            s.push_str(", ");
            s.push_str(&v);
        }
        s
    }

    fn str_parts(&mut self, parts: &[StrPart]) -> (String, Vec<String>) {
        let mut fmt = String::new();
        let mut vals = Vec::new();
        for p in parts {
            match p {
                StrPart::Lit(s) => fmt.push_str(&s.replace('{', "{{").replace('}', "}}")),
                StrPart::Interp(e, spec) => {
                    match spec {
                        Some(sp) => fmt.push_str(&format!("{{:{sp}}}")),
                        None => fmt.push_str("{}"),
                    }
                    vals.push(self.expr_loose(e));
                }
            }
        }
        (fmt, vals)
    }

    fn atom(&mut self, e: &Expr) -> String {
        let s = self.expr_loose(e);
        match e {
            Expr::Binary(..) | Expr::Unary(..) | Expr::Ref(..) | Expr::Range(..) => format!("({s})"),
            _ => s,
        }
    }

    /// Operand of a binary operator: parenthesize only when precedence requires.
    fn bin_child(&mut self, e: &Expr, parent: u8, right: bool) -> String {
        let s = self.expr_loose(e);
        let wrap = match e {
            Expr::Binary(_, op, _) => {
                let p = prec(op);
                p < parent || (right && p == parent) || (p == 3 && parent == 3)
            }
            Expr::Range(..) => true,
            _ => false,
        };
        if wrap { format!("({s})") } else { s }
    }

    /// String literals become `"x"` where a `&str` is expected and
    /// `String::from("x")` where an owned String is needed.
    fn expr_as(&mut self, e: &Expr, own: bool) -> String {
        match (e, own) {
            (Expr::Str(parts), false) => match parts.as_slice() {
                [StrPart::Lit(s)] => format!("\"{s}\""),
                _ => format!("&{}", self.expr(e)),
            },
            _ => self.expr(e),
        }
    }

    /// Expected type unknown (method args, operands, format args): plain
    /// literals stay `&'static str`, interpolated strings stay `String`.
    fn expr_loose(&mut self, e: &Expr) -> String {
        match e {
            Expr::Str(parts) if matches!(parts.as_slice(), [StrPart::Lit(_)]) => self.expr_as(e, false),
            _ => self.expr(e),
        }
    }

    fn expr(&mut self, e: &Expr) -> String {
        match e {
            Expr::Int(s) | Expr::Float(s) | Expr::Ident(s) => s.clone(),
            Expr::Bool(b) => b.to_string(),
            Expr::Str(parts) => match parts.as_slice() {
                [StrPart::Lit(s)] => format!("String::from(\"{s}\")"),
                _ => {
                    let a = self.fmt_args(&[e.clone()]);
                    format!("format!({a})")
                }
            },
            Expr::List(items) => {
                let v: Vec<String> = items.iter().map(|i| self.expr(i)).collect();
                format!("vec![{}]", v.join(", "))
            }
            Expr::Binary(l, op, r) => {
                let p = prec(op);
                let l = self.bin_child(l, p, false);
                let r = self.bin_child(r, p, true);
                format!("{l} {op} {r}")
            }
            Expr::Unary(op, x) => format!("{op}{}", self.atom(x)),
            Expr::Ref(x, m) => {
                let inner = match &**x {
                    Expr::Str(_) => self.expr(x),
                    _ => self.atom(x),
                };
                format!("&{}{inner}", if *m { "mut " } else { "" })
            }
            Expr::Range(lo, hi, inc) => {
                format!("{}{}{}", self.atom(lo), if *inc { "..=" } else { ".." }, self.atom(hi))
            }
            Expr::Call(name, args) => match name.as_str() {
                "print" => format!("println!({})", self.fmt_args(args)),
                "eprint" => format!("eprintln!({})", self.fmt_args(args)),
                "fail" => format!("anyhow::bail!({})", self.fmt_args(args)),
                _ => {
                    let params = self.fns.get(name).cloned().unwrap_or_default();
                    let a: Vec<String> = args
                        .iter()
                        .enumerate()
                        .map(|(i, x)| self.expr_as(x, params.get(i).is_none_or(owned)))
                        .collect();
                    format!("{name}({})", a.join(", "))
                }
            },
            Expr::StructLit(name, fields) => {
                let types = self.structs.get(name).cloned().unwrap_or_default();
                let f: Vec<String> = fields
                    .iter()
                    .map(|(n, v)| match v {
                        Expr::Ident(x) if x == n => n.clone(),
                        _ => format!("{n}: {}", self.expr_as(v, types.get(n).is_none_or(owned))),
                    })
                    .collect();
                format!("{name} {{ {} }}", f.join(", "))
            }
            Expr::Field(x, f) => format!("{}.{f}", self.atom(x)),
            Expr::Method(x, m, args) => {
                let recv = self.atom(x);
                let a: Vec<String> = args.iter().map(|x| self.expr_loose(x)).collect();
                format!("{recv}.{m}({})", a.join(", "))
            }
            Expr::Index(x, i) => format!("{}[{}]", self.atom(x), self.expr(i)),
            Expr::Try(x) => format!("{}?", self.atom(x)),
        }
    }
}

fn prec(op: &str) -> u8 {
    match op {
        "||" => 1,
        "&&" => 2,
        "==" | "!=" | "<" | ">" | "<=" | ">=" => 3,
        "+" | "-" => 5,
        _ => 6,
    }
}

fn is_diverging(e: &Expr) -> bool {
    matches!(e, Expr::Call(n, _) if n == "fail")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{lexer::lex, parser::parse};

    fn rs(src: &str) -> String {
        generate(&parse(lex(src).unwrap()).unwrap())
    }

    #[test]
    fn variables_and_reassignment() {
        let out = rs("fn main():\n    x = 10\n    ~count = 0\n    count = count + x\n    count += 1\n    x = 5\n");
        assert!(out.contains("let x = 10;"));
        assert!(out.contains("let mut count = 0;"));
        assert!(out.contains("count = count + x;"));
        assert!(out.contains("count += 1;"));
        assert!(out.contains("let x = 5;"), "immutable rebinding shadows");
    }

    #[test]
    fn functions_and_tail_return() {
        let out = rs("fn add(a: i32, b: i32) -> i32:\n    ret a + b\n");
        assert!(out.contains("fn add(a: i32, b: i32) -> i32 {\n    a + b\n}"));
    }

    #[test]
    fn fallible() {
        let out = rs("fn p(s: &str) -> i32!:\n    if s == \"\":\n        fail(\"empty\")\n    n: i32 = s.parse()?\n    ret n\nfn main()!:\n    p(\"1\")?\n");
        assert!(out.contains("fn p(s: &str) -> anyhow::Result<i32> {"));
        assert!(out.contains("anyhow::bail!(\"empty\");"));
        assert!(out.contains("let n: i32 = s.parse()?;"));
        assert!(out.contains("    Ok(n)\n"));
        assert!(out.contains("fn main() -> anyhow::Result<()> {"));
        assert!(out.contains("p(\"1\")?;\n    Ok(())"));
    }

    #[test]
    fn structs_and_types() {
        let out = rs("type User: name: str, age: u8, tags: [str], boss: str?\n");
        assert!(out.contains(
            "#[derive(Debug, Clone)]\nstruct User {\n    name: String,\n    age: u8,\n    tags: Vec<String>,\n    boss: Option<String>,\n}"
        ));
        assert_eq!(rust_type(&Type::Ref(Box::new(Type::List(Box::new(Type::Named("i32".into(), vec![])))), true)), "&mut [i32]");
    }

    #[test]
    fn print_and_interpolation() {
        let out = rs("fn main():\n    u = User(name: \"A\", age: 3)\n    print(\"hi {u.name} {u:?} {{}}\")\n    print(\"n\", 1 + 2)\n    s = \"x={u.age * 2}\"\n");
        assert!(out.contains("let u = User { name: String::from(\"A\"), age: 3 };"));
        assert!(out.contains("println!(\"hi {} {:?} {{}}\", u.name, u);"));
        assert!(out.contains("println!(\"n {}\", 1 + 2);"));
        assert!(out.contains("let s = format!(\"x={}\", u.age * 2);"));
    }

    #[test]
    fn control_flow() {
        let out = rs("fn main():\n    for i in 0..10:\n        if i % 2 == 0: continue\n        elif i > 7: break\n        else: print(i)\n    while not done(): stop()\n");
        assert!(out.contains("for i in 0..10 {"));
        assert!(out.contains("if i % 2 == 0 {\n            continue;\n        } else if i > 7 {\n            break;\n        } else {"));
        assert!(out.contains("while !done() {"));
    }

    #[test]
    fn string_literal_coercion() {
        let out = rs("type U: n: str\nfn own(s: str):\n    ret\nfn borrow(s: &str) -> str:\n    ret \"r\"\nfn main():\n    own(\"a\")\n    borrow(\"b\")\n    u = U(n: \"c\")\n    ok = u.n.starts_with(\"d\") and u.n == \"e\"\n");
        assert!(out.contains("own(String::from(\"a\"));"));
        assert!(out.contains("borrow(\"b\");"));
        assert!(out.contains("    String::from(\"r\")\n"));
        assert!(out.contains("U { n: String::from(\"c\") }"));
        assert!(out.contains("u.n.starts_with(\"d\") && u.n == \"e\""));
        let out = rs("fn b(s: &str):\n    ret\nfn main():\n    v.push(\"x {n}\")\n    b(\"y {n}\")\n    r = &\"z\"\n");
        assert!(out.contains("v.push(format!(\"x {}\", n));"));
        assert!(out.contains("b(&format!(\"y {}\", n));"));
        assert!(out.contains("let r = &String::from(\"z\");"));
    }

    #[test]
    fn minimal_parens() {
        let out = rs("fn f():\n    x = (a + b) * c - (d - e) + -f\n    y = (a == b) == c or x and y\n    z = (0..n).len()\n");
        assert!(out.contains("let x = (a + b) * c - (d - e) + -f;"));
        assert!(out.contains("let y = (a == b) == c || x && y;"));
        assert!(out.contains("let z = (0..n).len();"));
    }
}
