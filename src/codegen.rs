/// Uniform JSON errors: axum's plain-text rejections (malformed JSON 422,
/// bad query/path 400, 405, 413, ...) become {"error": ...} with the same
/// status. Also stamps security headers on every response.
async fn json_errors(res: axum::response::Response) -> axum::response::Response {
    use axum::response::IntoResponse;
    let status = res.status();
    let is_json = res
        .headers()
        .get(axum::http::header::CONTENT_TYPE)
        .and_then(|v| v.to_str().ok())
        .is_some_and(|v| v.starts_with("application/json") || v.starts_with("text/html"));
    let mut res = if is_json || !(status.is_client_error() || status.is_server_error()) {
        res
    } else {
        let bytes = axum::body::to_bytes(res.into_body(), 64 * 1024).await.unwrap_or_default();
        let mut msg = String::from_utf8_lossy(&bytes).trim().to_string();
        if status.is_server_error() {
            // never echo internal text from a 5xx
            msg = status.canonical_reason().unwrap_or("error").to_lowercase();
        } else if msg.is_empty() {
            msg = status.canonical_reason().unwrap_or("error").to_string();
        }
        let mut r = (status, axum::Json(serde_json::json!({ "error": msg }))).into_response();
        if std::env::var_os("PARVEZ_FUZZ").is_some() {
            // `parvez fuzz` coverage: this request was rejected before any handler ran
            r.headers_mut().insert("x-parvez-rejected", axum::http::HeaderValue::from_static("1"));
        }
        r
    };
    let h = res.headers_mut();
    h.insert("x-content-type-options", axum::http::HeaderValue::from_static("nosniff"));
    h.insert("x-frame-options", axum::http::HeaderValue::from_static("DENY"));
    h.insert("cache-control", axum::http::HeaderValue::from_static("no-store"));
    h.insert("referrer-policy", axum::http::HeaderValue::from_static("no-referrer"));
    res
}

