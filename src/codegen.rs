    /// Compiler fuzzing: random programs built from hostile fragments must make
    /// the lexer, parser, validator and code generator return Ok or Err, never
    /// panic. Deterministic (seeded), so failures reproduce.
    #[test]
    fn fuzz_compiler_never_panics() {
        // the compiler runs on a 64 MB thread (main.rs); fuzz under the same stack
        std::thread::Builder::new().stack_size(64 << 20).spawn(fuzz_body).unwrap().join().unwrap();
    }

    fn fuzz_body() {
        const FRAGS: &[&str] = &[
            "fn ", "main", "()", ":", "\n", "    ", "\t", "x", " = ", "~", "ret ", "if ", "elif ", "else", "for ", " in ",
            "while ", "loop", "match ", " -> ", "|", "_", "(", ")", "[", "]", "{", "}", ",", ".", "..", "..=", "?", "!",
            "&", "*", "+", "-", "\"", "\"\"\"", "'", "'a'", "'\\n'", "\\", "\\u{0}", "{x}", "{{", "}}", "1", "1.5",
            "\"s {a.b} {c:?}\"", "type ", "enum ", "impl ", "use ", "import ", "route ", "socket ", "state", "@json\n",
            "@guard(g)\n", "@rename(\"t\")\n", "@body_error(400, \"x\")\n", "GET ", "\"/a/{id}\"", "(req, auth, conn)",
            "@embed_dir(\"dist\")\n", "const N: i32 = ", "if let Some(v) = ", " else: ",
            "spawn ", "move ", "async ", "fn(i32) -> str", "str?", "[u8]", "#c\n", "😀", "\r\n", ";", "=", "==", "not ",
        ];
        let mut seed: u64 = 0x9e37_79b9_7f4a_7c15;
        let mut next = || {
            seed ^= seed << 13;
            seed ^= seed >> 7;
            seed ^= seed << 17;
            seed
        };
        // Mutation fuzzing: real programs with 1-3 random edits, so most
        // mutants still parse and drive validation, codegen and the linter.
        const SEEDS: &[&str] = &[
            "const N: i32 = if true: 2 else: 0\nfn main():\n    if let Some(x) = Some(N): print(x)\n",
            include_str!("../examples/hello.prvz"),
            include_str!("../examples/service.prvz"),
            "fn f(req) -> str!:\n    a, ~b = pair()\n    c = '!'\n    s = \"\"\"\n        x {a}\n        \"\"\"\n    ret s\n@guard(f)\n@protocols(\"p\")\nsocket \"/ws/{id}\" (auth, id: str, conn):\n    loop:\n        match conn.recv().await?:\n            Some(m) -> conn.sender().send(&m)\n            None -> break\n",
            "async fn main()!:\n    xs = [1, 2]\n    ys: [i32] = xs.iter()\n        .map(|x| x * 2)\n        .collect()\n    h = spawn:\n        print(\"\\u{2713} {ys:?}\")\n    h.await?\n",
        ];
        let cases: u64 = std::env::var("PARVEZ_FUZZ_CASES").ok().and_then(|v| v.parse().ok()).unwrap_or(3000);
        let mut generated = 0u64;
        for case in 0..cases {
            let seed_src = SEEDS[(next() % SEEDS.len() as u64) as usize];
            let mut chars: Vec<char> = seed_src.chars().collect();
            for _ in 0..1 + next() % 3 {
                let at = (next() as usize) % (chars.len() + 1);
                match next() % 4 {
                    0 => chars.splice(at..at, FRAGS[(next() % FRAGS.len() as u64) as usize].chars()).for_each(drop),
                    1 => {
                        let end = (at + 1 + (next() % 8) as usize).min(chars.len());
                        chars.drain(at.min(end)..end);
                    }
                    2 => {
                        let end = (at + (next() % 40) as usize).min(chars.len());
                        let dup: Vec<char> = chars[at.min(end)..end].to_vec();
                        chars.splice(at..at, dup).for_each(drop);
                    }
                    _ => {
                        // balanced nesting around a value, up to past MAX_DEPTH
                        let n = (next() % 320) as usize;
                        let deep: String = format!("{}1{}", "(".repeat(n), ")".repeat(n));
                        chars.splice(at..at, deep.chars()).for_each(drop)
                    }
                }
            }
            let src: String = chars.into_iter().collect();
            let run = std::panic::catch_unwind(|| {
                let Ok(toks) = lex(&src) else { return false };
                let Ok(items) = crate::parser::parse_items(toks) else { return false };
                let prog = Program { items, modules: vec![], files: vec![] };
                if crate::parser::validate(&prog).is_err() {
                    return false;
                }
                let _ = generate_mapped(&prog);
                let _ = crate::security::lint(&prog);
                true
            });
            match run {
                Ok(reached) => generated += reached as u64,
                Err(_) => panic!("case {case} panicked on input:\n{src:?}"),
            }
        }
        assert!(generated > cases / 20, "fuzz inputs too shallow: only {generated} of {cases} reached codegen");
    }

