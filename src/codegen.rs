//! AST -> idiomatic, formatted Rust source. Type checking and borrow
//! checking are delegated to rustc.
//!
//! Every emitted line is tagged with the `.prvz` line it came from, giving a
//! source map that `diagnostics` uses to point rustc errors at `.prvz` lines.

use crate::ast::*;
use crate::deps::crate_of;
use crate::parser::path_params;
use std::collections::{BTreeSet, HashMap};

/// Generated Rust plus its source map: `map[i]` is the `.prvz` line for
/// Rust line `i + 1` (0 = no source line, e.g. the header).
pub struct Generated {
    pub code: String,
    pub map: Vec<usize>,
    /// external crates the program needs (module names, e.g. `serde_json`)
    pub deps: BTreeSet<String>,
}

#[cfg(test)]
pub fn generate(prog: &Program) -> String {
    generate_mapped(prog).code
}

pub fn generate_mapped(prog: &Program) -> Generated {
    let mut g = Gen::new(prog);
    g.out.push_str("// Generated by parvez v0.3. Plain Rust, no runtime: safe to keep and edit by hand.\n");
    g.out.push_str("#![allow(unused)]\n");
    g.deps.insert("anyhow".into());
    let uses: Vec<&UseDef> = prog.items.iter().filter_map(|i| if let Item::Use(u) = i { Some(u) } else { None }).collect();
    if !uses.is_empty() {
        g.out.push('\n');
        for u in uses {
            g.gen_use(u);
        }
    }
    let mut routes = Vec::new();
    for item in &prog.items {
        match item {
            Item::Use(_) => continue,
            Item::Route(r) => {
                routes.push(r);
                continue;
            }
            _ => g.out.push('\n'),
        }
        match item {
            Item::Struct(s) => g.gen_struct(s),
            Item::Enum(e) => g.gen_enum(e),
            Item::Impl(i) => g.gen_impl(i),
            Item::Fn(f) => g.gen_fn(f),
            Item::Use(_) | Item::Route(_) => unreachable!(),
        }
    }
    if !routes.is_empty() {
        g.gen_service(&routes);
    }
    let mut out = finish(&g.out);
    out.deps = g.deps;
    out
}

/// Append `// @prvz:N` to each Rust line that starts a new `.prvz` line.
pub fn annotate(g: &Generated) -> String {
    let mut out = String::new();
    let mut prev = 0;
    for (i, l) in g.code.lines().enumerate() {
        out.push_str(l);
        let n = g.map.get(i).copied().unwrap_or(0);
        let t = l.trim();
        if n != 0 && n != prev && !t.is_empty() && t != "}" && t != "};" {
            out.push_str(&format!("  // @prvz:{n}"));
        }
        prev = n;
        out.push('\n');
    }
    out
}

// Line markers embedded during generation, stripped by `finish`.
const MARK_START: char = '\u{1}';
const MARK_END: char = '\u{2}';

fn finish(raw: &str) -> Generated {
    let mut code = String::with_capacity(raw.len());
    let mut map = Vec::new();
    let mut last = 0;
    for l in raw.lines() {
        if let Some(a) = l.find(MARK_START) {
            let b = l[a..].find(MARK_END).map(|b| a + b).unwrap_or(a);
            last = l[a + 1..b].parse().unwrap_or(last);
            code.push_str(&l[..a]);
            code.push_str(&l[b + 1..]);
        } else {
            code.push_str(l);
        }
        code.push('\n');
        map.push(last);
    }
    Generated { code, map, deps: BTreeSet::new() }
}

#[derive(Default)]
struct Gen {
    out: String,
    indent: usize,
    /// `.prvz` line of the construct being emitted
    cur_line: usize,
    /// name -> is_mutable, one map per lexical block
    scopes: Vec<HashMap<String, bool>>,
    fallible: bool,
    ret_ty: Option<Type>,
    /// type whose `impl` block is being emitted (resolves `Self`)
    cur_impl: Option<String>,
    /// fn name (or `Type::fn`) -> parameter types, for string-literal coercion
    fns: HashMap<String, Vec<Type>>,
    /// method name -> parameter types (None if the name is ambiguous)
    methods: HashMap<String, Option<Vec<Type>>>,
    /// struct name -> field types
    structs: HashMap<String, HashMap<String, Type>>,
    /// variant name -> [(enum name, data)]
    variants: HashMap<String, Vec<(String, VariantData)>>,
    deps: BTreeSet<String>,
}

/// Does a value of this type need an owned String (vs a borrowed `&str`)?
fn owned(t: &Type) -> bool {
    !matches!(t, Type::Ref(..))
}

pub fn rust_type(t: &Type) -> String {
    match t {
        Type::Named(n, args) => {
            let base = if n == "str" { "String" } else { n.as_str() };
            if args.is_empty() {
                base.to_string()
            } else {
                let a: Vec<String> = args.iter().map(rust_type).collect();
                format!("{base}<{}>", a.join(", "))
            }
        }
        Type::Ref(inner, m) => {
            let m = if *m { "mut " } else { "" };
            match &**inner {
                Type::Named(n, a) if n == "str" && a.is_empty() => format!("&{m}str"),
                Type::List(e) => format!("&{m}[{}]", rust_type(e)),
                other => format!("&{m}{}", rust_type(other)),
            }
        }
        Type::List(e) => format!("Vec<{}>", rust_type(e)),
        Type::Opt(e) => format!("Option<{}>", rust_type(e)),
    }
}

impl Gen {
    fn new(prog: &Program) -> Self {
        let mut g = Gen::default();
        let param_types = |f: &FnDef| f.params.iter().map(|(_, t)| t.clone()).collect::<Vec<_>>();
        for item in &prog.items {
            match item {
                Item::Fn(f) => {
                    g.fns.insert(f.name.clone(), param_types(f));
                }
                Item::Struct(s) => {
                    g.structs.insert(s.name.clone(), s.fields.iter().cloned().collect());
                }
                Item::Enum(e) => {
                    for v in &e.variants {
                        g.variants
                            .entry(v.name.clone())
                            .or_default()
                            .push((e.name.clone(), v.data.clone()));
                    }
                }
                Item::Use(_) | Item::Route(_) => {}
                Item::Impl(i) => {
                    for m in &i.methods {
                        g.fns.insert(format!("{}::{}", i.ty, m.name), param_types(m));
                        g.methods
                            .entry(m.name.clone())
                            .and_modify(|e| *e = None)
                            .or_insert_with(|| Some(param_types(m)));
                    }
                }
            }
        }
        g
    }

    fn line(&mut self, s: &str) {
        for _ in 0..self.indent {
            self.out.push_str("    ");
        }
        if self.cur_line > 0 {
            self.out.push(MARK_START);
            self.out.push_str(&self.cur_line.to_string());
            self.out.push(MARK_END);
        }
        self.out.push_str(s);
        self.out.push('\n');
    }

    fn derive_line(&mut self, attrs: &Attrs) -> String {
        let mut d = vec!["Debug".to_string(), "Clone".into(), "PartialEq".into()];
        if attrs.json {
            self.deps.insert("serde".into());
            d.push("serde::Serialize".into());
            d.push("serde::Deserialize".into());
        }
        for x in &attrs.derives {
            if !d.contains(x) {
                d.push(x.clone());
            }
        }
        format!("#[derive({})]", d.join(", "))
    }

    fn gen_use(&mut self, u: &UseDef) {
        self.cur_line = u.line;
        if let Some(c) = crate_of(&u.path, false) {
            self.deps.insert(c);
        }
        // `use reqwest` alone only declares the dependency.
        if u.path.contains("::") {
            self.line(&format!("use {};", u.path));
        }
    }

    fn gen_struct(&mut self, s: &StructDef) {
        self.cur_line = s.line;
        let d = self.derive_line(&s.attrs);
        self.line(&d);
        self.line(&format!("struct {} {{", s.name));
        self.indent += 1;
        for (name, ty) in &s.fields {
            self.line(&format!("{name}: {},", rust_type(ty)));
        }
        self.indent -= 1;
        self.line("}");
    }

    fn gen_enum(&mut self, e: &EnumDef) {
        self.cur_line = e.line;
        let d = self.derive_line(&e.attrs);
        self.line(&d);
        self.line(&format!("enum {} {{", e.name));
        self.indent += 1;
        for v in &e.variants {
            let body = match &v.data {
                VariantData::Unit => String::new(),
                VariantData::Tuple(ts) => {
                    format!("({})", ts.iter().map(rust_type).collect::<Vec<_>>().join(", "))
                }
                VariantData::Named(fs) => {
                    let f: Vec<String> =
                        fs.iter().map(|(n, t)| format!("{n}: {}", rust_type(t))).collect();
                    format!(" {{ {} }}", f.join(", "))
                }
            };
            self.line(&format!("{}{body},", v.name));
        }
        self.indent -= 1;
        self.line("}");
    }

    fn gen_impl(&mut self, i: &ImplDef) {
        self.cur_line = i.line;
        self.cur_impl = Some(i.ty.clone());
        self.line(&format!("impl {} {{", i.ty));
        self.indent += 1;
        for (k, m) in i.methods.iter().enumerate() {
            if k > 0 {
                self.out.push('\n');
            }
            self.gen_fn(m);
        }
        self.indent -= 1;
        self.cur_line = i.line;
        self.line("}");
        self.cur_impl = None;
    }

    fn gen_fn(&mut self, f: &FnDef) {
        self.cur_line = f.line;
        let mut params: Vec<String> = Vec::new();
        if let Some(r) = f.receiver {
            params.push(
                match r {
                    Receiver::Ref => "&self",
                    Receiver::RefMut => "&mut self",
                    Receiver::Value => "self",
                    Receiver::MutValue => "mut self",
                }
                .into(),
            );
        }
        params.extend(f.params.iter().map(|(n, t)| format!("{n}: {}", rust_type(t))));
        let ret = match (&f.ret, f.fallible) {
            (None, false) => String::new(),
            (None, true) => " -> anyhow::Result<()>".into(),
            (Some(t), false) => format!(" -> {}", rust_type(t)),
            (Some(t), true) => format!(" -> anyhow::Result<{}>", rust_type(t)),
        };
        let kw = if f.is_async { "async fn" } else { "fn" };
        if f.is_async && f.name == "main" && self.cur_impl.is_none() {
            self.deps.insert("tokio".into());
            self.line("#[tokio::main]");
        }
        self.line(&format!("{kw} {}({}){} {{", f.name, params.join(", "), ret));
        self.fallible = f.fallible;
        self.ret_ty = f.ret.clone();
        self.indent += 1;
        let mut scope: HashMap<String, bool> = f.params.iter().map(|(n, _)| (n.clone(), false)).collect();
        if f.receiver.is_some() {
            scope.insert("self".into(), false);
        }
        self.scopes.push(scope);

        let (last, init) = match f.body.split_last() {
            Some((l, i)) => (Some(l), i),
            None => (None, &f.body[..]),
        };
        for s in init {
            self.gen_stmt(s);
        }
        // Tail position: idiomatic implicit return.
        if let Some(l) = last {
            self.cur_line = l.line;
        }
        match last.map(|l| &l.stmt) {
            Some(Stmt::Ret(Some(e))) => {
                let v = self.ret_expr(e);
                self.line(&self.wrap_ok(v));
            }
            Some(Stmt::Ret(None)) => {
                if f.fallible {
                    self.line("Ok(())");
                }
            }
            Some(Stmt::Expr(e)) if f.ret.is_some() && !is_diverging(e) => {
                let v = self.ret_expr(e);
                self.line(&self.wrap_ok(v));
            }
            Some(s) => {
                self.gen_stmt(last.unwrap());
                if f.fallible && f.ret.is_none() && !matches!(s, Stmt::Expr(e) if is_diverging(e)) {
                    self.line("Ok(())");
                }
            }
            None => {
                if f.fallible {
                    self.line("Ok(())");
                }
            }
        }

        self.scopes.pop();
        self.indent -= 1;
        self.line("}");
    }

    fn ret_expr(&mut self, e: &Expr) -> String {
        let o = self.ret_ty.as_ref().is_none_or(owned);
        self.expr_as(e, o)
    }

    fn wrap_ok(&self, v: String) -> String {
        if self.fallible { format!("Ok({v})") } else { v }
    }

    fn block(&mut self, stmts: &[Located], binds: &[String]) {
        self.indent += 1;
        self.scopes.push(binds.iter().map(|b| (b.clone(), false)).collect());
        for s in stmts {
            self.gen_stmt(s);
        }
        self.scopes.pop();
        self.indent -= 1;
    }

    fn is_mutable(&self, name: &str) -> bool {
        self.scopes.iter().rev().find_map(|s| s.get(name)).copied().unwrap_or(false)
    }

    fn is_local(&self, name: &str) -> bool {
        self.scopes.iter().any(|s| s.contains_key(name))
    }

    fn gen_stmt(&mut self, located: &Located) {
        self.cur_line = located.line;
        match &located.stmt {
            Stmt::Let { name, mutable, ty, value } => {
                let v = self.expr_as(value, ty.as_ref().is_none_or(owned));
                if !mutable && ty.is_none() && self.is_mutable(name) {
                    self.line(&format!("{name} = {v};"));
                    return;
                }
                self.scopes.last_mut().unwrap().insert(name.clone(), *mutable);
                let m = if *mutable { "mut " } else { "" };
                let t = ty.as_ref().map(|t| format!(": {}", rust_type(t))).unwrap_or_default();
                self.line(&format!("let {m}{name}{t} = {v};"));
            }
            Stmt::Assign { target, op, value } => {
                let t = self.expr(target);
                let v = self.expr(value);
                self.line(&format!("{t} {op} {v};"));
            }
            Stmt::Expr(Expr::Match(scrut, arms)) => {
                let m = self.gen_match(scrut, arms, false);
                self.line(&m);
            }
            Stmt::Expr(e) => {
                let v = self.expr(e);
                self.line(&format!("{v};"));
            }
            Stmt::Ret(e) => {
                let v = match e {
                    Some(e) => self.ret_expr(e),
                    None => "()".into(),
                };
                let v = if self.fallible {
                    format!("Ok({v})")
                } else if e.is_none() {
                    String::new()
                } else {
                    v
                };
                if v.is_empty() {
                    self.line("return;");
                } else {
                    self.line(&format!("return {v};"));
                }
            }
            Stmt::If { branches, els } => {
                for (i, (cond, body)) in branches.iter().enumerate() {
                    let c = self.expr(cond);
                    if i == 0 {
                        self.line(&format!("if {c} {{"));
                    } else {
                        self.line(&format!("}} else if {c} {{"));
                    }
                    self.block(body, &[]);
                }
                if let Some(body) = els {
                    self.line("} else {");
                    self.block(body, &[]);
                }
                self.line("}");
            }
            Stmt::For { var, iter, body } => {
                let it = self.expr(iter);
                self.line(&format!("for {var} in {it} {{"));
                self.block(body, std::slice::from_ref(var));
                self.line("}");
            }
            Stmt::While { cond, body } => {
                let c = self.expr(cond);
                self.line(&format!("while {c} {{"));
                self.block(body, &[]);
                self.line("}");
            }
            Stmt::Break => self.line("break;"),
            Stmt::Continue => self.line("continue;"),
        }
    }

    // ---------- HTTP service ----------

    /// Each `route` becomes an async fn (the user's body, normal codegen),
    /// an axum handler wrapping it, and one generated `#[tokio::main]`.
    fn gen_service(&mut self, routes: &[&RouteDef]) {
        for d in ["tokio", "axum", "serde", "serde_json"] {
            self.deps.insert(d.into());
        }
        self.cur_line = 0;
        self.out.push('\n');
        for l in SERVICE_PRELUDE.lines() {
            self.line(l);
        }
        let mut table: Vec<(String, Vec<(String, String)>)> = Vec::new(); // path -> [(method, handler)]
        for r in routes {
            let mut name = route_fn_name(r);
            while self.fns.contains_key(&name) {
                name.push('_');
            }
            self.fns.insert(name.clone(), r.params.iter().map(|(_, t)| t.clone()).collect());
            let f = FnDef {
                name: name.clone(),
                is_async: true,
                receiver: None,
                params: r.params.clone(),
                ret: r.ret.clone(),
                fallible: r.fallible,
                body: r.body.clone(),
                line: r.line,
            };
            self.out.push('\n');
            self.gen_fn(&f);

            // axum handler: extractors in order Path, Query, Json (body last)
            self.cur_line = r.line;
            let ty_of = |n: &str| r.params.iter().find(|(p, _)| p == n).map(|(_, t)| rust_type(t));
            let mut ex = Vec::new();
            let holes = path_params(&r.path);
            match holes.as_slice() {
                [] => {}
                [one] => ex.push(format!("axum::extract::Path({one}): axum::extract::Path<{}>", ty_of(one).unwrap())),
                many => {
                    let ts: Vec<String> = many.iter().map(|h| ty_of(h).unwrap()).collect();
                    ex.push(format!("axum::extract::Path(({})): axum::extract::Path<({})>", many.join(", "), ts.join(", ")));
                }
            }
            if let Some(t) = ty_of("query") {
                ex.push(format!("axum::extract::Query(query): axum::extract::Query<{t}>"));
            }
            if let Some(t) = ty_of("body") {
                ex.push(format!("axum::Json(body): axum::Json<{t}>"));
            }
            let args: Vec<&str> = r.params.iter().map(|(p, _)| p.as_str()).collect();
            let call = format!("{name}({}).await", args.join(", "));
            let text = matches!(&r.ret, Some(Type::Named(n, a)) if n == "str" && a.is_empty());
            let (ret, body) = match (&r.ret, r.fallible) {
                (None, false) => (String::new(), format!("{call};")),
                (None, true) => (" -> Result<(), AppError>".into(), format!("Ok({call}?)")),
                (Some(_), false) if text => (" -> String".into(), call),
                (Some(t), false) => (format!(" -> axum::Json<{}>", rust_type(t)), format!("axum::Json({call})")),
                (Some(_), true) if text => (" -> Result<String, AppError>".into(), format!("Ok({call}?)")),
                (Some(t), true) => (
                    format!(" -> Result<axum::Json<{}>, AppError>", rust_type(t)),
                    format!("Ok(axum::Json({call}?))"),
                ),
            };
            let handler = format!("{name}_http");
            self.out.push('\n');
            self.line(&format!("/// {} {}", r.method, r.path));
            self.line(&format!("async fn {handler}({}){ret} {{", ex.join(", ")));
            self.indent += 1;
            self.line(&body);
            self.indent -= 1;
            self.line("}");
            match table.iter_mut().find(|(p, _)| *p == r.path) {
                Some((_, v)) => v.push((r.method.to_lowercase(), handler)),
                None => table.push((r.path.clone(), vec![(r.method.to_lowercase(), handler)])),
            }
        }

        self.cur_line = routes[0].line;
        self.out.push('\n');
        self.line("#[tokio::main]");
        self.line("async fn main() -> anyhow::Result<()> {");
        self.indent += 1;
        self.line("let app = axum::Router::new()");
        self.indent += 1;
        for (path, methods) in &table {
            let chain: Vec<String> = methods.iter().map(|(m, h)| format!("{m}({h})")).collect();
            self.line(&format!(".route(\"{path}\", axum::routing::{})", chain.join(".")));
        }
        self.indent -= 1;
        self.line(";");
        self.line("let port = std::env::var(\"PORT\").unwrap_or_else(|_| \"8080\".into());");
        self.line("let addr = format!(\"0.0.0.0:{port}\");");
        self.line("let listener = tokio::net::TcpListener::bind(&addr).await?;");
        self.line("println!(\"listening on http://{addr}\");");
        self.line("axum::serve(listener, app).await?;");
        self.line("Ok(())");
        self.indent -= 1;
        self.line("}");
    }

    // ---------- match ----------

    /// Emits a (possibly multi-line) `match`. In value position each arm
    /// yields its last expression; in statement position arms are `()`.
    fn gen_match(&mut self, scrut: &Expr, arms: &[Arm], value: bool) -> String {
        let saved_line = self.cur_line;
        let mut s = self.atom(scrut);
        if arms.iter().any(|a| has_str_pat(&a.pat)) {
            // `&x[..]` is `&str` for String, &str and &String alike.
            s = format!("&{s}[..]");
        }
        let saved_out = std::mem::take(&mut self.out);
        let base = self.indent;
        self.indent += 1;
        for arm in arms {
            self.cur_line = arm.line;
            let mut binds = Vec::new();
            let pat = self.pattern(&arm.pat, &mut binds);
            self.scopes.push(binds.iter().map(|b| (b.clone(), false)).collect());
            let guard = match &arm.guard {
                Some(g) => format!(" if {}", self.expr(g)),
                None => String::new(),
            };
            let head = format!("{pat}{guard} =>");
            match arm.body.as_slice() {
                [Located { stmt: Stmt::Expr(e), .. }] if value || is_macro_call(e) => {
                    self.cur_line = arm.body[0].line;
                    let v = self.expr(e);
                    self.line(&format!("{head} {v},"));
                }
                body => {
                    self.line(&format!("{head} {{"));
                    self.indent += 1;
                    let (last, init) = body.split_last().expect("arm body is never empty");
                    for st in init {
                        self.gen_stmt(st);
                    }
                    match &last.stmt {
                        Stmt::Expr(e) if value => {
                            self.cur_line = last.line;
                            let v = self.expr(e);
                            self.line(&v);
                        }
                        _ => self.gen_stmt(last),
                    }
                    self.indent -= 1;
                    self.line("}");
                }
            }
            self.scopes.pop();
        }
        self.indent = base;
        let arms_src = std::mem::replace(&mut self.out, saved_out);
        self.cur_line = saved_line;
        format!("match {s} {{\n{arms_src}{}}}", "    ".repeat(base))
    }

    /// Resolve a variant name to its qualified path and shape.
    fn variant(&self, name: &str) -> Option<(String, VariantData)> {
        if let Some((prefix, v)) = name.rsplit_once("::") {
            let en = if prefix == "Self" { self.cur_impl.clone()? } else { prefix.to_string() };
            let (_, data) = self.variants.get(v)?.iter().find(|(e, _)| *e == en)?;
            return Some((name.to_string(), data.clone()));
        }
        match self.variants.get(name)?.as_slice() {
            [(en, data)] => Some((format!("{en}::{name}"), data.clone())),
            _ => None, // unknown or ambiguous: leave as written
        }
    }

    fn pattern(&mut self, p: &Pat, binds: &mut Vec<String>) -> String {
        match p {
            Pat::Wild => "_".into(),
            Pat::Rest => "..".into(),
            Pat::Bind(n) => {
                binds.push(n.clone());
                n.clone()
            }
            Pat::Lit(e) => self.expr_as(e, false),
            Pat::Range(lo, hi, inc) => {
                let lo = self.expr_as(lo, false);
                let hi = self.expr_as(hi, false);
                format!("{lo}{}{hi}", if *inc { "..=" } else { ".." })
            }
            Pat::Or(alts) => alts.iter().map(|a| self.pattern(a, binds)).collect::<Vec<_>>().join(" | "),
            Pat::Variant(name, subs) => {
                let resolved = self.variant(name);
                let path = resolved.as_ref().map(|(p, _)| p.clone()).unwrap_or_else(|| name.clone());
                let fields = match &resolved {
                    Some((_, VariantData::Named(fs))) => Some(fs.iter().map(|(n, _)| n.clone()).collect::<Vec<_>>()),
                    _ => None,
                };
                let arity = match &resolved {
                    Some((_, VariantData::Tuple(ts))) => Some(ts.len()),
                    Some((_, VariantData::Named(fs))) => Some(fs.len()),
                    _ => None,
                };
                let Some(subs) = subs else {
                    return match (&resolved, fields) {
                        (_, Some(_)) => format!("{path} {{ .. }}"),
                        (Some((_, VariantData::Tuple(_))), _) => format!("{path}(..)"),
                        _ => path,
                    };
                };
                let has_rest = subs.iter().any(|(_, p)| *p == Pat::Rest);
                let rest = !has_rest && arity.is_some_and(|n| subs.len() < n);
                let named_form = fields.is_some() || subs.iter().any(|(f, _)| f.is_some());
                let mut parts = Vec::new();
                for (i, (f, sp)) in subs.iter().enumerate() {
                    let pat = self.pattern(sp, binds);
                    if !named_form || *sp == Pat::Rest {
                        parts.push(pat);
                        continue;
                    }
                    let fname = f.clone().or_else(|| fields.as_ref().and_then(|fs| fs.get(i).cloned()));
                    match fname {
                        Some(fname) if pat == fname => parts.push(fname),
                        Some(fname) => parts.push(format!("{fname}: {pat}")),
                        None => parts.push(pat),
                    }
                }
                if rest {
                    parts.push("..".into());
                }
                if named_form {
                    format!("{path} {{ {} }}", parts.join(", "))
                } else {
                    format!("{path}({})", parts.join(", "))
                }
            }
        }
    }

    // ---------- expressions ----------

    /// Builds the `"fmt", args...` part of a formatting macro.
    fn fmt_args(&mut self, args: &[Expr]) -> String {
        let mut fmt = Vec::new();
        let mut vals = Vec::new();
        for a in args {
            match a {
                Expr::Str(parts) => {
                    let (f, v) = self.str_parts(parts);
                    fmt.push(f);
                    vals.extend(v);
                }
                other => {
                    fmt.push("{}".into());
                    vals.push(self.expr_loose(other));
                }
            }
        }
        let mut s = format!("\"{}\"", fmt.join(" "));
        for v in vals {
            s.push_str(", ");
            s.push_str(&v);
        }
        s
    }

    fn str_parts(&mut self, parts: &[StrPart]) -> (String, Vec<String>) {
        let mut fmt = String::new();
        let mut vals = Vec::new();
        for p in parts {
            match p {
                StrPart::Lit(s) => fmt.push_str(&s.replace('{', "{{").replace('}', "}}")),
                StrPart::Interp(e, spec) => {
                    match spec {
                        Some(sp) => fmt.push_str(&format!("{{:{sp}}}")),
                        None => fmt.push_str("{}"),
                    }
                    vals.push(self.expr_loose(e));
                }
            }
        }
        (fmt, vals)
    }

    fn atom(&mut self, e: &Expr) -> String {
        let s = self.expr_loose(e);
        match e {
            Expr::Binary(..) | Expr::Unary(..) | Expr::Ref(..) | Expr::Range(..) => format!("({s})"),
            _ => s,
        }
    }

    /// Operand of a binary operator: parenthesize only when precedence requires.
    fn bin_child(&mut self, e: &Expr, parent: u8, right: bool) -> String {
        let s = self.expr_loose(e);
        let wrap = match e {
            Expr::Binary(_, op, _) => {
                let p = prec(op);
                p < parent || (right && p == parent) || (p == 3 && parent == 3)
            }
            Expr::Range(..) => true,
            _ => false,
        };
        if wrap { format!("({s})") } else { s }
    }

    /// String literals become `"x"` where a `&str` is expected and
    /// `String::from("x")` where an owned String is needed.
    fn expr_as(&mut self, e: &Expr, own: bool) -> String {
        match (e, own) {
            (Expr::Str(parts), false) => match parts.as_slice() {
                [StrPart::Lit(s)] => format!("\"{s}\""),
                _ => format!("&{}", self.expr(e)),
            },
            _ => self.expr(e),
        }
    }

    /// Expected type unknown (method args, operands, format args): plain
    /// literals stay `&'static str`, interpolated strings stay `String`.
    fn expr_loose(&mut self, e: &Expr) -> String {
        match e {
            Expr::Str(parts) if matches!(parts.as_slice(), [StrPart::Lit(_)]) => self.expr_as(e, false),
            _ => self.expr(e),
        }
    }

    /// Arguments coerced against known parameter types (unknown -> owned).
    fn args_for(&mut self, args: &[Expr], params: &[Type]) -> Vec<String> {
        args.iter()
            .enumerate()
            .map(|(i, x)| self.expr_as(x, params.get(i).is_none_or(owned)))
            .collect()
    }

    /// `name: value` list for struct / struct-variant literals, with shorthand.
    fn field_inits(&mut self, fields: &[(String, Expr)], types: &HashMap<String, Type>) -> String {
        let f: Vec<String> = fields
            .iter()
            .map(|(n, v)| match v {
                Expr::Ident(x) if x == n => n.clone(),
                _ => format!("{n}: {}", self.expr_as(v, types.get(n).is_none_or(owned))),
            })
            .collect();
        f.join(", ")
    }

    fn expr(&mut self, e: &Expr) -> String {
        match e {
            Expr::Int(s) | Expr::Float(s) => s.clone(),
            Expr::Ident(s) if crate_of(s, true).is_some() => {
                self.deps.extend(crate_of(s, true));
                s.clone()
            }
            Expr::Ident(s) => match self.variant(s) {
                Some((path, VariantData::Unit)) if !self.is_local(s) => path,
                _ => s.clone(),
            },
            Expr::Bool(b) => b.to_string(),
            Expr::Str(parts) => match parts.as_slice() {
                [StrPart::Lit(s)] => format!("String::from(\"{s}\")"),
                _ => {
                    let a = self.fmt_args(&[e.clone()]);
                    format!("format!({a})")
                }
            },
            Expr::List(items) => {
                let v: Vec<String> = items.iter().map(|i| self.expr(i)).collect();
                format!("vec![{}]", v.join(", "))
            }
            Expr::Binary(l, op, r) => {
                let p = prec(op);
                let l = self.bin_child(l, p, false);
                let r = self.bin_child(r, p, true);
                format!("{l} {op} {r}")
            }
            Expr::Unary(op, x) => format!("{op}{}", self.atom(x)),
            Expr::Ref(x, m) => {
                let inner = match &**x {
                    Expr::Str(_) => self.expr(x),
                    _ => self.atom(x),
                };
                format!("&{}{inner}", if *m { "mut " } else { "" })
            }
            Expr::Range(lo, hi, inc) => {
                format!("{}{}{}", self.atom(lo), if *inc { "..=" } else { ".." }, self.atom(hi))
            }
            Expr::Call(name, generics, args) => match name.as_str() {
                "print" => format!("println!({})", self.fmt_args(args)),
                "eprint" => format!("eprintln!({})", self.fmt_args(args)),
                "fail" => match args.split_first() {
                    // fail(404, "msg") -> HTTP status in routes
                    Some((Expr::Int(code), rest)) if !rest.is_empty() => {
                        format!("anyhow::bail!(HttpError({code}, format!({})))", self.fmt_args(rest))
                    }
                    _ => format!("anyhow::bail!({})", self.fmt_args(args)),
                },
                "json_encode" | "json_pretty" if args.len() == 1 => {
                    self.deps.insert("serde_json".into());
                    let f = if name == "json_encode" { "to_string" } else { "to_string_pretty" };
                    let a = match &args[0] {
                        Expr::Ref(..) => self.expr(&args[0]),
                        other => format!("&{}", self.atom(other)),
                    };
                    format!("serde_json::{f}({a})")
                }
                "json_decode" if args.len() == 1 => {
                    self.deps.insert("serde_json".into());
                    let a = match &args[0] {
                        Expr::Str(_) => self.expr_as(&args[0], false),
                        Expr::Ref(..) => self.expr(&args[0]),
                        other => format!("&{}", self.atom(other)),
                    };
                    format!("serde_json::from_str{}({a})", turbofish(generics))
                }
                _ => match self.variant(name) {
                    Some((path, VariantData::Tuple(types))) => {
                        format!("{path}({})", self.args_for(args, &types).join(", "))
                    }
                    Some((path, VariantData::Named(fields))) => {
                        // positional args for a struct-like variant
                        let named: Vec<(String, Expr)> =
                            fields.iter().map(|(n, _)| n.clone()).zip(args.iter().cloned()).collect();
                        let types = fields.into_iter().collect();
                        format!("{path} {{ {} }}", self.field_inits(&named, &types))
                    }
                    _ => {
                        let key = match (name.strip_prefix("Self::"), &self.cur_impl) {
                            (Some(m), Some(t)) => format!("{t}::{m}"),
                            _ => name.clone(),
                        };
                        let params = self.fns.get(&key).cloned().unwrap_or_default();
                        self.deps.extend(crate_of(name, true));
                        format!("{name}{}({})", turbofish(generics), self.args_for(args, &params).join(", "))
                    }
                },
            },
            Expr::StructLit(name, fields) => {
                if let Some((path, VariantData::Named(fs))) = self.variant(name) {
                    let types = fs.into_iter().collect();
                    return format!("{path} {{ {} }}", self.field_inits(fields, &types));
                }
                let sname = match (name.as_str(), &self.cur_impl) {
                    ("Self", Some(t)) => t.clone(),
                    _ => name.clone(),
                };
                let types = self.structs.get(&sname).cloned().unwrap_or_default();
                format!("{name} {{ {} }}", self.field_inits(fields, &types))
            }
            Expr::Field(x, f) => format!("{}.{f}", self.atom(x)),
            Expr::Method(x, m, generics, args) => {
                let recv = self.atom(x);
                let a = match self.methods.get(m).cloned().flatten() {
                    Some(params) => self.args_for(args, &params),
                    None => args.iter().map(|x| self.expr_loose(x)).collect(),
                };
                format!("{recv}.{m}{}({})", turbofish(generics), a.join(", "))
            }
            Expr::Await(x) => format!("{}.await", self.atom(x)),
            Expr::Index(x, i) => format!("{}[{}]", self.atom(x), self.expr(i)),
            Expr::Try(x) => format!("{}?", self.atom(x)),
            Expr::Match(s, arms) => self.gen_match(s, arms, true),
        }
    }
}

fn prec(op: &str) -> u8 {
    match op {
        "||" => 1,
        "&&" => 2,
        "==" | "!=" | "<" | ">" | "<=" | ">=" => 3,
        "+" | "-" => 5,
        _ => 6,
    }
}

fn is_diverging(e: &Expr) -> bool {
    matches!(e, Expr::Call(n, _, _) if n == "fail")
}

fn is_macro_call(e: &Expr) -> bool {
    matches!(e, Expr::Call(n, _, _) if matches!(n.as_str(), "print" | "eprint" | "fail"))
}

fn turbofish(generics: &[Type]) -> String {
    if generics.is_empty() {
        String::new()
    } else {
        format!("::<{}>", generics.iter().map(rust_type).collect::<Vec<_>>().join(", "))
    }
}

/// `POST "/users/{id}"` -> `post_users_id`
fn route_fn_name(r: &RouteDef) -> String {
    let mut n = r.method.to_lowercase();
    for seg in r.path.split('/').filter(|s| !s.is_empty()) {
        n.push('_');
        n.extend(seg.chars().map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_lowercase() } else { '_' }));
    }
    if r.path == "/" {
        n.push_str("_root");
    }
    while n.contains("__") {
        n = n.replace("__", "_");
    }
    n.trim_end_matches('_').to_string()
}

/// Error plumbing emitted once per service: route `!` errors -> JSON responses.
const SERVICE_PRELUDE: &str = r#"/// `fail(status, "msg")` inside a route -> that HTTP status + {"error": msg}.
#[derive(Debug)]
struct HttpError(u16, String);

impl std::fmt::Display for HttpError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.1)
    }
}

impl std::error::Error for HttpError {}

/// Any route error -> JSON body; non-HttpError errors become 500.
struct AppError(anyhow::Error);

impl<E: Into<anyhow::Error>> From<E> for AppError {
    fn from(e: E) -> Self {
        AppError(e.into())
    }
}

impl axum::response::IntoResponse for AppError {
    fn into_response(self) -> axum::response::Response {
        let (code, msg) = match self.0.downcast_ref::<HttpError>() {
            Some(HttpError(code, msg)) => (*code, msg.clone()),
            None => (500, format!("{:#}", self.0)),
        };
        let status = axum::http::StatusCode::from_u16(code)
            .unwrap_or(axum::http::StatusCode::INTERNAL_SERVER_ERROR);
        (status, axum::Json(serde_json::json!({ "error": msg }))).into_response()
    }
}"#;

fn has_str_pat(p: &Pat) -> bool {
    match p {
        Pat::Lit(Expr::Str(_)) => true,
        Pat::Or(a) => a.iter().any(has_str_pat),
        _ => false,
    }
}

